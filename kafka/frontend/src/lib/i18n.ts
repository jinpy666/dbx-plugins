export function resolveWorkbenchLocale(locale: string): WorkbenchLocale {
  const normalized = locale.replace("_", "-");
  if (normalized.toLowerCase().startsWith("zh-tw") || normalized.toLowerCase().startsWith("zh-hk")) return "zh-TW";
  if (normalized.toLowerCase().startsWith("zh")) return "zh-CN";
  if (normalized.toLowerCase().startsWith("pt")) return "pt-BR";
  const language = normalized.split("-")[0] as WorkbenchLocale;
  return language in messages ? language : "zh-CN";
}

// Shared reactive locale so every component can call `t(...)` in templates
// (App.vue keeps it in sync with the host locale / appearance events).
export const workbenchLocale = ref<WorkbenchLocale>("zh-CN");

export function setWorkbenchLocale(next: string) {
  workbenchLocale.value = resolveWorkbenchLocale(next);
}

export function t(key: string, values: Record<string, string | number> = {}): string {
  return workbenchMessage(workbenchLocale.value, key, values);
}

export function workbenchMessage(locale: string, key: string, values: Record<string, string | number> = {}): string {
  const resolved = resolveWorkbenchLocale(locale);
  const lookup = (source: unknown): unknown =>
    key.split(".").reduce<unknown>((value, part) => (value && typeof value === "object" ? (value as Record<string, unknown>)[part] : undefined), source);
  const nested = lookup(messages[resolved]);
  const fallback = lookup(messages.en);
  const template = typeof nested === "string" ? nested : typeof fallback === "string" ? fallback : key;
  return template.replace(/\{(\w+)\}/g, (_match, name: string) => String(values[name] ?? `{${name}}`));
}
